import { promises as fs } from 'node:fs';
import path from 'node:path';

const docsRoot = path.resolve('docs');
const outputPath = path.join(docsRoot, 'index.md');

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(fullPath));
    else if (entry.isFile() && entry.name.endsWith('.md') && fullPath !== outputPath) files.push(fullPath);
  }

  return files;
}

function titleFrom(content, filePath) {
  const heading = content.match(/^#\s+(.+)$/m)?.[1]?.trim();
  return heading || path.basename(filePath, '.md');
}

const files = await walk(docsRoot);
const groups = new Map();

for (const file of files) {
  const relative = path.relative(docsRoot, file).split(path.sep).join('/');
  const section = relative.includes('/') ? relative.split('/')[0] : 'root';
  const content = await fs.readFile(file, 'utf8');
  const item = { relative, title: titleFrom(content, file) };
  if (!groups.has(section)) groups.set(section, []);
  groups.get(section).push(item);
}

const lines = [
  '# Generated Documentation Index',
  '',
  '> Generated by `node scripts/generate-doc-index.mjs`. Do not edit manually.',
  '',
];

for (const [section, items] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`## ${section}`);
  lines.push('');
  for (const item of items) lines.push(`- [${item.title}](${item.relative})`);
  lines.push('');
}

await fs.writeFile(outputPath, `${lines.join('\n').trim()}\n`, 'utf8');
console.log(`Generated ${path.relative(process.cwd(), outputPath)} with ${files.length} entries.`);
