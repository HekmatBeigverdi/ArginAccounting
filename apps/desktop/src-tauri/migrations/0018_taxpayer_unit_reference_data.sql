CREATE TABLE taxpayer_unit_reference_sets (
  dataset_version TEXT PRIMARY KEY NOT NULL,
  source_name TEXT NOT NULL,
  source_uri TEXT,
  source_digest TEXT,
  applied_at TEXT NOT NULL,
  is_current INTEGER NOT NULL DEFAULT 0 CHECK (is_current IN (0, 1))
);

CREATE UNIQUE INDEX ux_taxpayer_unit_reference_sets_current
  ON taxpayer_unit_reference_sets(is_current)
  WHERE is_current = 1;

CREATE TABLE taxpayer_units (
  code TEXT PRIMARY KEY NOT NULL,
  title TEXT NOT NULL,
  dataset_version TEXT NOT NULL,
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  FOREIGN KEY (dataset_version) REFERENCES taxpayer_unit_reference_sets(dataset_version)
);

CREATE INDEX ix_taxpayer_units_title ON taxpayer_units(title);
CREATE INDEX ix_taxpayer_units_active ON taxpayer_units(is_active, title);

